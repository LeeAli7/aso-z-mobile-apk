const DIM = "#6F6F77";
const LIGHT = "#EDEDEF";
const CYCLE = 2400;

export function WaitLabel({
  style,
  active = true,
}: {
  style?: StyleProp<TextStyle>;
  active?: boolean;
}) {
  const [i, setI] = useState(() => Math.floor(Math.random() * PHRASES.length));
  const glow = useSharedValue(0);
  const fade = useSharedValue(1);

  const next = useCallback(() => {
    setI((v) => (v + 1 + Math.floor(Math.random() * 3)) % PHRASES.length);
  }, []);

  useEffect(() => {
    if (!active) return;
    glow.value = withRepeat(
      withTiming(1, { duration: 2600, easing: Easing.inOut(Easing.quad) }),
      -1,
      true,
    );
    const t = setInterval(() => {
      fade.value = withTiming(0, { duration: 170 }, (fin) => {
        if (fin) runOnJS(next)();
      });
    }, CYCLE);
    return () => {
      clearInterval(t);
      glow.value = 0;
    };
  }, [active, glow, fade, next]);

  useEffect(() => {
    if (active) fade.value = withTiming(1, { duration: 260 });
  }, [i, active, fade]);

  const st = useAnimatedStyle(() => ({
    opacity: fade.value,
    color: interpolateColor(glow.value, [0, 1], [DIM, LIGHT]),
  }));

  return (
    <Reanimated.Text
      numberOfLines={1}
      accessibilityLabel="Агент работает"
      style={[{ fontSize: 13, letterSpacing: 0.1 }, st, style]}
    >
      {PHRASES[i]}
    </Reanimated.Text>
  );
}
