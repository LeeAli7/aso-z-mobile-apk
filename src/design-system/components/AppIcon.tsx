export function materialToApp(name: string): AppIconName {
  return MATERIAL_TO_APP[name] ?? "more";
}

export function AppIcon({
  name,
  size = 22,
  color = "#fff",
  strokeWidth = STROKE_DEFAULT,
}: {
  name: AppIconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
}) {
  const glyph = ICON_XML[ICON_ALIAS[name] ?? name] || ICON_XML.circle;
  const xml =
    `<svg viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" ` +
    `stroke-linecap="round" stroke-linejoin="round">${glyph.replace(/__C__/g, color)}</svg>`;
  return <SvgXml xml={xml} width={size} height={size} />;
}
